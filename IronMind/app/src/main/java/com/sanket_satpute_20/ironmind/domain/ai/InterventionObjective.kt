package com.sanket_satpute_20.ironmind.domain.ai

/**
 * Represents the semantic purpose or behavioral objective of an intervention.
 * Distinct from InterventionType, which represents the tactic used.
 */
enum class InterventionObjective {
    INITIATE_ACTION,
    REDUCE_FRICTION,
    RECOVER_COMMITMENT,
    PREVENT_DISRUPTION,
    REINFORCE_BEHAVIOR,
    EXTRACT_INSIGHT
}
